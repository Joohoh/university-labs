/* Fazer um programa com valores fixados por atribuição aos coeficientes
coeficienteA, coeficienteB e coeficienteC de uma equação quadrática.
Calcular e imprimir o valor do discriminante (delta). Delta =
coeficienteB
2
- 4 * coeficienteA * coeficienteC.  */

const coeficienteA = 2;
const coeficienteB = 4;
const coeficienteC = 5;

const delta = (coeficienteB ** 2) - (4 * coeficienteA * coeficienteC);

console.log("Valor do discriminante (delta) = " + delta);
